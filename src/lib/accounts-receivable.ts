export type ReceivableStatus =
  | "unpaid"
  | "partially_paid"
  | "paid"
  | "disputed";

export type RentalChargeType =
  | "base_rent"
  | "cam_nnn"
  | "late_fee"
  | "parking_storage";

export type MiscChargeType =
  | "application_fee"
  | "damage_reimbursement"
  | "key_access"
  | "utility_reimbursement"
  | "other";

export type ReceivableKind = "rental" | "miscellaneous";

