/** CAM / NNN recoveries are billed quarterly to each property's anchor tenant. */
const CAM_RECOVERIES: { code: string; amount: number }[] = [
  { code: "NR", amount: 3200 },
  { code: "BA", amount: 2800 },
  { code: "MS", amount: 1900 },
];

const CAM_MONTHS = [0, 3];

function leaseOf(code: string) {
  const lease = SEED_RENT_ROLL.find((entry) => entry.code === code);
  if (!lease) throw new Error(`Unknown seeded lease code: ${code}`);
  return lease;
}

function rentalRow(input: {
  lease: Lease;
  monthsAgo: number;
  category: RentalChargeType;
  amount: number;
  received: number;
  disputed?: boolean;
  invoiceDay: number;
  dueDay: number;
  notes?: string;
  description: string;
  idSuffix: string;
  referencePrefix: string;
}): Receivable {
  const {
    lease,
    monthsAgo,
    category,
    amount,
    received,
    disputed = false,
    invoiceDay,
    dueDay,
    notes = "",
    description,
    idSuffix,
    referencePrefix,
  } = input;

  const slug = monthSlug(monthsAgo);
  const receivableId = `${referencePrefix}-${slug}-${lease.code}`;
  const invoiceDate = monthDay(monthsAgo, invoiceDay);

  return {
    id: `ar-${idSuffix}-${slug}-${lease.code}`.toLowerCase(),
    receivableId,
    kind: "rental",
    customerName: lease.customerName,
    customerId: lease.customerId,
    property: lease.property,
    unit: lease.unit,
    period: monthPeriodLabel(monthsAgo),
    category,
    amount,
    amountReceived: received,
    disputed,
    invoiceDate,
    dueDate: monthDay(monthsAgo, dueDay),
    paymentMethod: received > 0 ? "ACH" : "",
    paymentReference: received > 0 ? `PMT-${slug.replace("-", "")}-${lease.code}` : "",
    fileName: `${receivableId.toLowerCase()}.pdf`,
    description,
    notes,
    createdAt: invoiceDate,
  };
}

export function seedRentalReceivables(): Receivable[] {
  const rows: Receivable[] = [];

  for (let monthsAgo = SEED_MONTHS - 1; monthsAgo >= 0; monthsAgo -= 1) {
    for (const lease of SEED_RENT_ROLL) {
      const exception = RENT_EXCEPTIONS[`${monthsAgo}:${lease.code}`];
      const received = exception
        ? (exception.received ?? lease.rent)
        : lease.rent;

      rows.push(
        rentalRow({
          lease,
          monthsAgo,
          category: "base_rent",
          amount: lease.rent,
          received,
          disputed: exception?.disputed ?? false,
          invoiceDay: 1,
          dueDay: 5,
          notes: exception?.notes ?? "",
          description: `Monthly base rent for ${lease.property} · ${lease.unit}.`,
          idSuffix: "rent",
          referencePrefix: "RENT",
        })
      );
    }

    if (CAM_MONTHS.includes(monthsAgo)) {
      for (const recovery of CAM_RECOVERIES) {
        const lease = leaseOf(recovery.code);
        const collected = monthsAgo > 0 || lease.code === "NR";

        rows.push(
          rentalRow({
            lease,
            monthsAgo,
            category: "cam_nnn",
            amount: recovery.amount,
            received: collected ? recovery.amount : 0,
            invoiceDay: 1,
            dueDay: 10,
            notes: collected
              ? ""
              : "Quarterly CAM / NNN recovery billed; payment not yet received.",
            description: `Quarterly CAM / NNN recovery for ${lease.property} · ${lease.unit}.`,
            idSuffix: "cam",
            referencePrefix: "CAM",
          })
        );
      }
    }
  }

  const cedar = leaseOf("CD");
  rows.push(
    rentalRow({
      lease: cedar,
      monthsAgo: 0,
      category: "late_fee",
      amount: 150,
      received: 0,
      invoiceDay: 6,
      dueDay: 20,
      notes:
        "Late fee applied automatically under the lease after rent went unpaid past the grace period.",
      description: `Late fee on current-month rent for ${cedar.property} · ${cedar.unit}.`,
      idSuffix: "late",
      referencePrefix: "LATE",
    })
  );

  const quietHarbor = leaseOf("QH");
  rows.push(
    rentalRow({
      lease: quietHarbor,
      monthsAgo: 0,
      category: "parking_storage",
      amount: 600,
      received: 600,
      invoiceDay: 1,
      dueDay: 15,
      description: `Reserved parking for ${quietHarbor.property} · ${quietHarbor.unit}.`,
      idSuffix: "park",
      referencePrefix: "PARK",
    })
  );

  return rows;
}

